 await page.getByRole('button',{name:'Tìm nguồn & đối chiếu',exact:true}).click()
 await expect(page.locator('.eval-faith-card')).toHaveCount(2)
 await expect(page.locator('.eval-inline-note')).toContainText('Chưa có điểm faithfulness cho cấu hình đang chọn')
