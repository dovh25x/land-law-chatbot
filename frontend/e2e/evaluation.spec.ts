import {test,expect} from '@playwright/test'
import {readFile} from 'node:fs/promises'
const archive=JSON.parse(await readFile(new URL('../../reports/public-evaluations.json',import.meta.url),'utf8'))
const active='corpus-a26bc99e541fbbe2'
const full=archive.runs.find((r:{configuration_sha256:string})=>r.configuration_sha256.startsWith('8db2d701'))
const probe=archive.runs.find((r:{configuration_sha256:string})=>r.configuration_sha256.startsWith('380801c7'))
const payload={...archive,default_run_id:full.id,active_release:active,active_configuration_sha256:'fixture-current',runs:archive.runs.map((r:{release:string})=>({...r,matches_active_release:r.release===active,matches_active_configuration:false}))}
test.beforeEach(async({page})=>{
 await page.route('**/readyz',r=>r.fulfill({json:{status:'ready',database:true,corpus_release:active}}))
 await page.route('**/api/v1/status',r=>r.fulfill({json:{generation_available:true,reason:null}}))
 await page.route('**/api/v1/documents',r=>r.fulfill({json:{documents:[]}}))
 await page.route('**/api/v1/evaluations/latest',r=>r.fulfill({json:payload}))
 await page.goto('/')
 const menu=page.getByRole('button',{name:'Mở menu điều hướng'});if(await menu.isVisible())await menu.click()
 await page.getByRole('button',{name:'Đánh giá hệ thống',exact:true}).click()
})
test('shows failed outcomes without hiding previous configurations and exports every published artifact',async({page})=>{
 await expect(page.locator('.stat-pass strong')).toHaveText('22/32')
 await expect(page.locator('.stat-fail strong')).toHaveText('7')
 await expect(page.locator('.eval-suite-card').filter({hasText:'Câu hỏi tự nhiên'})).toContainText('2/6 câu nội dung đạt đủ yêu cầu')
 await page.getByLabel('Lọc kết quả',{exact:true}).selectOption('fail')
 await expect(page.locator('.eval-case')).toHaveCount(7)
 await page.getByLabel('Tìm ca đánh giá').fill('N02')
 await page.locator('.eval-case summary').click()
 await expect(page.locator('.eval-case-body')).toContainText('khoản 2 Điều 19')
 await expect(page.locator('.eval-case-body a')).toHaveAttribute('href',/reviewed-postgresql-attempt-5\/natural/)
 const pending=page.waitForEvent('download');await page.getByRole('button',{name:'Tải số liệu'}).click()
 const download=await pending;const downloaded=JSON.parse(await readFile((await download.path())!,'utf8'))
 expect(downloaded.sources).toHaveLength(63)
 expect(downloaded.runs.find((r:{id:string})=>r.id===probe.id).suites[0].counts.not_run).toBe(7)
})
test('record metrics appear first while current results, samples and failures remain available',async({page})=>{
 const highlights=page.getByRole('region',{name:'Kết quả nổi bật đã ghi nhận'})
 await expect(highlights.locator('[data-metric="smoke"] .eval-highlight-value')).toHaveText('95%')
 await expect(highlights.locator('[data-metric="smoke"]')).toContainText('19/20 ca đạt đủ tiêu chí')
 await expect(highlights.locator('[data-metric="smoke"]')).toContainText('Kết quả lịch sử · corpus khác')
 await expect(highlights.locator('[data-metric="recall"] .eval-highlight-value')).toHaveText('100%')
 await expect(highlights.locator('[data-metric="recall"]')).toContainText('3 ca có gold · Bộ bổ sung')
 await expect(highlights.locator('[data-metric="recall"]')).toContainText('PostgreSQL')
 await expect(highlights.locator('[data-metric="faithfulness"] .eval-highlight-value')).toHaveText('92,3%')
 await expect(highlights.locator('[data-metric="faithfulness"]')).toContainText('6/8 ca có điểm · 13 mệnh đề')
 await expect(page.getByLabel('Lần đánh giá',{exact:true})).toHaveValue(full.id)
 await expect(page.locator('.stat-fail strong')).toHaveText('7')
 const first=await highlights.boundingBox(),details=await page.locator('#evaluation-run-details').boundingBox()
 expect(first!.y).toBeLessThan(details!.y)
 await page.getByRole('button',{name:'Xem toàn bộ kết quả và các ca chưa đạt'}).click()
 await expect(page.locator('#evaluation-run-details')).toBeInViewport()
})
test('incomplete attempts remain selectable with unexecuted cases in the denominator',async({page})=>{
 await page.getByRole('button',{name:'Lịch sử đánh giá',exact:true}).click()
 await expect(page.locator('.eval-history-row')).toHaveCount(13)
 await page.getByLabel('Lần đánh giá',{exact:true}).selectOption(probe.id)
 await expect(page.locator('.stat-pass strong')).toHaveText('0/8')
 await expect(page.locator('.stat-not_run strong')).toHaveText('7')
 await page.getByLabel('Lọc kết quả',{exact:true}).selectOption('not_run')
 await expect(page.locator('.eval-case')).toHaveCount(7)
})
